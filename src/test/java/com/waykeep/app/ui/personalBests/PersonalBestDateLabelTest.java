package com.waykeep.app.ui.personalBests;

import static org.junit.Assert.assertEquals;

import org.junit.Test;

import java.time.OffsetDateTime;
import java.util.Locale;

public class PersonalBestDateLabelTest {

    @Test
    public void formatsACompactLocalDateWithoutOffsetOrWeekday() {
        OffsetDateTime start = OffsetDateTime.parse("2026-10-15T07:14:19+05:30");

        assertEquals("Oct 15, 2026 · 07:14",
                PersonalBestsActivity.formatTrackDateTime(start, Locale.US));
    }

    @Test
    public void doesNotRepeatAnAutoGeneratedTimestampAsTheTrackName() {
        OffsetDateTime start = OffsetDateTime.parse("2026-10-15T07:14:00+05:30");

        assertEquals("Oct 15, 2026 · 07:14",
                PersonalBestsActivity.formatTrackLine("2026-10-15T07:14+0530", start,
                        Locale.US, "%1$s · %2$s"));
    }

    @Test
    public void keepsACustomTrackNameAlongsideTheCompactDate() {
        OffsetDateTime start = OffsetDateTime.parse("2026-10-15T07:14:00+05:30");

        assertEquals("Morning loop · Oct 15, 2026 · 07:14",
                PersonalBestsActivity.formatTrackLine("Morning loop", start,
                        Locale.US, "%1$s · %2$s"));
    }
}
