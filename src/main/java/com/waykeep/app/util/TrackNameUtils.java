package com.waykeep.app.util;

import android.content.Context;
import android.text.format.DateUtils;

import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Locale;

import com.waykeep.app.R;
import com.waykeep.app.data.models.Track;
import com.waykeep.app.settings.PreferencesUtils;

/**
 * Utilities for track name.
 *
 * @author Matthew Simmons
 */
public class TrackNameUtils {

    private TrackNameUtils() {
    }

    //TODO Should not access sharedPreferences; trackName should be an ENUM.
    public static String getTrackName(Context context, Track.Id trackId, OffsetDateTime startTime) {
        String trackName = PreferencesUtils.getString(R.string.track_name_key, context.getString(R.string.track_name_default));

        if (trackName.equals(context.getString(R.string.settings_recording_track_name_date_local_value))) {
            return StringUtils.formatDateTimeWithOffset(startTime);
        } else if (trackName.equals(context.getString(R.string.settings_recording_track_name_date_iso_8601_value))) {
            return startTime.format(DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mmX"));
        } else {
            return context.getString(R.string.track_name_format, trackId.id());
        }
    }

    /**
     * True when the stored name is one of the auto-generated timestamp forms for this track's
     * start time (ISO or local), independent of the *current* naming preference — which may have
     * changed since the track was recorded. Custom names ("Evening Ride", "Track 7") return false.
     */
    public static boolean isAutoGeneratedName(String name, OffsetDateTime startTime) {
        if (name == null || name.isEmpty()) {
            return false;
        }
        if (name.equals(startTime.format(DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mmX")))) {
            return true;
        }
        return name.equals(StringUtils.formatDateTimeWithOffset(startTime));
    }

    /**
     * List-view title for auto-generated names: "28 Oct 26". Storage keeps the timestamp.
     */
    public static String formatListDate(OffsetDateTime startTime) {
        return startTime.format(DateTimeFormatter.ofPattern("dd MMM yy", Locale.getDefault()));
    }

    /**
     * Detail-header title for auto-generated names. DateUtils keeps the field order, month
     * names and RTL behaviour in the device locale instead of a hardcoded pattern.
     */
    public static String formatDisplayDate(Context context, OffsetDateTime startTime) {
        return DateUtils.formatDateTime(context, startTime.toInstant().toEpochMilli(),
                DateUtils.FORMAT_SHOW_WEEKDAY | DateUtils.FORMAT_ABBREV_WEEKDAY
                        | DateUtils.FORMAT_SHOW_DATE | DateUtils.FORMAT_ABBREV_MONTH);
    }
}
